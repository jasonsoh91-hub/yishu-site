// Generates lib/world-map.ts from Natural Earth (world-atlas, 110m) with d3-geo.
// Run: npm run build:map  (only needed if you change MARKETS below)
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { geoEquirectangular, geoPath } from "d3-geo";
import { feature } from "topojson-client";

const require = createRequire(import.meta.url);
const topo = JSON.parse(readFileSync(require.resolve("world-atlas/countries-110m.json"), "utf8"));
const countries = feature(topo, topo.objects.countries).features.filter(
  (f) => f.properties.name !== "Antarctica",
);

// code -> [lon, lat, atlas name (null if too small for 110m)]
const MARKETS = {
  CN: [104.0, 35.0, "China"],
  KR: [127.8, 36.3, "South Korea"],
  JP: [138.5, 36.5, "Japan"],
  TW: [121.0, 23.7, "Taiwan"],
  HK: [114.17, 22.3, null],
  TH: [101.0, 15.0, "Thailand"],
  MY: [101.7, 3.1, "Malaysia"],
  SG: [103.8, 1.35, null],
  ID: [113.0, -1.5, "Indonesia"],
  AU: [134.0, -25.0, "Australia"],
  US: [-98.0, 39.0, "United States of America"],
  CA: [-106.0, 56.0, "Canada"],
};

const W = 1000, H = 470;
const projection = geoEquirectangular().fitExtent([[4, 4], [W - 4, H - 4]], {
  type: "FeatureCollection",
  features: countries,
});
const path = geoPath(projection).digits(1);
const active = new Set(Object.values(MARKETS).map((m) => m[2]).filter(Boolean));

const land = [], activeLand = [];
for (const f of countries) {
  const d = path(f);
  if (!d) continue;
  (active.has(f.properties.name) ? activeLand : land).push(d);
}
const pins = Object.fromEntries(
  Object.entries(MARKETS).map(([code, [lon, lat]]) => {
    const [x, y] = projection([lon, lat]);
    return [code, { x: +x.toFixed(1), y: +y.toFixed(1) }];
  }),
);

const out = `// GENERATED by scripts/build-map.mjs from Natural Earth via world-atlas. Do not edit by hand.
export const MAP_VIEWBOX = "0 0 ${W} ${H}";
export const LAND_PATH = ${JSON.stringify(land.join(""))};
export const ACTIVE_LAND_PATH = ${JSON.stringify(activeLand.join(""))};
export const PINS: Record<string, { x: number; y: number }> = ${JSON.stringify(pins)};
`;
writeFileSync(new URL("../lib/world-map.ts", import.meta.url), out);
console.log("wrote lib/world-map.ts", out.length, "bytes");

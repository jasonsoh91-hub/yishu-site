// Generates lib/world-map.ts from Natural Earth (world-atlas, 110m) with d3-geo.
// Run: npm run build:map  (only needed if you change MARKETS below)
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { geoEquirectangular, geoPath } from "d3-geo";
import { feature } from "topojson-client";

const require = createRequire(import.meta.url);
const topo = JSON.parse(readFileSync(require.resolve("world-atlas/countries-110m.json"), "utf8"));
const countries = feature(topo, topo.objects.countries).features.filter(
  (f) => f.properties.name !== "Antarctica",
);

// code -> [lon, lat, atlas name (null if too small for 110m), label side]
// Label sides follow the client's "Global Market Map" slide.
const MARKETS = {
  CN: [108.0, 34.0, "China", "l"],
  KR: [127.8, 36.3, "South Korea", "t"],
  JP: [138.5, 36.5, "Japan", "r"],
  TW: [121.0, 23.7, "Taiwan", "r"],
  HK: [114.17, 22.3, null, "b"],
  TH: [101.0, 15.0, "Thailand", "l"],
  MY: [101.7, 3.6, "Malaysia", "l"],
  SG: [103.8, 1.35, null, "r"],
  ID: [113.0, -1.5, "Indonesia", "b"],
  AU: [134.0, -25.0, "Australia", "t"],
  US: [-98.0, 39.0, "United States of America", "r"],
  CA: [-100.0, 56.0, "Canada", "t"],
};

// Soft halos grouping markets, as on the slide.
const REGIONS = [["CN", "KR", "JP", "TW", "HK"], ["TH", "MY", "SG", "ID"], ["AU"], ["US", "CA"]];

// Pacific-centred crop (20°E → 60°W, 75°N → 50°S) so Asia-Pacific and North America sit side by side.
const W = 1000, H = 470;
const LON0 = 160, SPAN = 280, LAT_TOP = 75, LAT_BOTTOM = -50;
const k = W / ((SPAN * Math.PI) / 180);
const projection = geoEquirectangular()
  .rotate([-LON0, 0])
  .scale(k)
  .center([0, (LAT_TOP + LAT_BOTTOM) / 2])
  .translate([W / 2, H / 2])
  .clipExtent([[0, 0], [W, H]]);
const path = geoPath(projection).digits(1);
const active = new Set(Object.values(MARKETS).map((m) => m[2]).filter(Boolean));

const land = [], activeLand = [];
for (const f of countries) {
  const d = path(f);
  if (!d) continue;
  (active.has(f.properties.name) ? activeLand : land).push(d);
}
const pins = Object.fromEntries(
  Object.entries(MARKETS).map(([code, [lon, lat, , side]]) => {
    const [x, y] = projection([lon, lat]);
    return [code, { x: +x.toFixed(1), y: +y.toFixed(1), side }];
  }),
);
const regions = REGIONS.map((codes) => {
  const pts = codes.map((c) => pins[c]);
  const cx = pts.reduce((a, p) => a + p.x, 0) / pts.length;
  const cy = pts.reduce((a, p) => a + p.y, 0) / pts.length;
  const r = Math.max(...pts.map((p) => Math.hypot(p.x - cx, p.y - cy))) + 34;
  return { x: +cx.toFixed(1), y: +cy.toFixed(1), r: +r.toFixed(1) };
});

const out = `// GENERATED by scripts/build-map.mjs from Natural Earth via world-atlas. Do not edit by hand.
export const MAP_VIEWBOX = "0 0 ${W} ${H}";
export const LAND_PATH = ${JSON.stringify(land.join(""))};
export const ACTIVE_LAND_PATH = ${JSON.stringify(activeLand.join(""))};
export const PINS: Record<string, { x: number; y: number; side: "l" | "r" | "t" | "b" }> = ${JSON.stringify(pins)};
export const REGIONS: { x: number; y: number; r: number }[] = ${JSON.stringify(regions)};
`;
writeFileSync(new URL("../lib/world-map.ts", import.meta.url), out);
console.log("wrote lib/world-map.ts", out.length, "bytes");
